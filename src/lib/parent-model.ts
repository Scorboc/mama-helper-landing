export function stateWithProfile(state:ParentState,p:Profile):ParentState {
  const previous=state.profile;
  const changed=!previous||previous.stage!==p.stage||previous.birthDate!==p.birthDate||previous.week!==p.week||previous.weekDate!==p.weekDate;
  if(!changed)return {...state,profile:p};
  const events:ParentState['events']={};
  for(const m of milestones){if(m.stage===p.stage&&m.age<ageValue(p))events[m.id]={status:'hidden',until:0};}
  return {...state,profile:p,events};
}
const match = (text:string, expression:RegExp) => expression.test(text);

function profileContext(profile:Profile|null) {
  if (!profile) return 'Сначала заполните профиль — тогда помощник сможет учитывать возраст или срок. ';
  return '';
}

function listReply(profile:Profile|null, intro:string, steps:string[], ending?:string) {
  return `${profileContext(profile)}${intro}\n\n${steps.map((step,index)=>`${index+1}. ${step}`).join('\n')}${ending ? `\n\n${ending}` : ''}`;
}

function childAgeGroup(profile:Profile|null) {
  if (!profile || profile.stage !== 'child') return 'unknown';
  const months = ageValue(profile);
  if (months < 6) return '0-5';
  if (months < 12) return '6-11';
  if (months < 24) return '12-23';
  if (months >= 36 && months < 84) return 'preschool';
  return '24-36';
}

