import re

def norm(text):return str(text or '').lower().replace('ё','е')

def unwanted_thought_without_intent(text):
    q=norm(text)
    thought=bool(re.search(r'навязчив|пуга\w*[^.!?\n]{0,40}мысл|страшн\w*[^.!?\n]{0,30}(?:мысл|картин)|мысль[^.!?\n]{0,40}пуга',q))
    denial=bool(re.search(r'не хочу|не собираюсь|не желаю|намерения нет|нет намерения|этого не хочу',q))
    acute=bool(re.search(r'теряю контроль|не могу останов|сейчас[^.!?\n]{0,45}(?:ударю|убью|сделаю)|есть план|уже (?:ударил|ударила|начал)',q))
    return thought and denial and not acute

def choking(text):
    q=norm(text)
    return bool(re.search(r'поперх|подавил|удуш|не может[^.!?\n]{0,50}кашля|не может[^.!?\n]{0,50}вдох',q))

def choking_reply(age):
    call='Немедленно вызовите скорую помощь — 112 или 103 на громкой связи или поручите вызов другому взрослому. Если ребёнок не может эффективно кашлять или дышать, действуйте сразу, не ждите ответа чата.\n\n'
    infant=('До года: положите младенца лицом вниз на предплечье, опираясь на бедро; поддерживайте голову и шею, голову держите ниже груди. '
            'Сделайте до 5 ударов между лопатками, проверяя результат после каждого. Если не помогло, переверните на спину с поддержкой головы, '
            'положите на колени и сделайте до 5 резких надавливаний на нижнюю половину грудины двумя большими пальцами, обхватив грудную клетку руками. На живот младенцу не надавливают.')
    child=('С года: наклоните ребёнка вперёд и сделайте до 5 ударов между лопатками. Если не помогло, встаньте сзади, '
           'поместите кулак между пупком и нижним концом грудины, обхватите второй рукой и сделайте до 5 толчков внутрь и вверх.')
    body=infant if age is not None and age<12 else child if age is not None else infant+'\n\n'+child
    return call+body+('\n\nПовторяйте эти циклы, пока ребёнок в сознании и препятствие сохраняется. При эффективном кашле не делайте удары или толчки — поощряйте кашель и наблюдайте. '
        'Не доставайте предмет вслепую. Если ребёнок потерял сознание, положите на твёрдую поверхность и начинайте СЛР по указаниям диспетчера: '
        '5 начальных спасательных вдохов, затем 30 надавливаний и 2 вдоха. Обученные детской СЛР по схеме 15:2 используют её. '
        'Если вдохи сделать не получается, выполняйте надавливания, следуя диспетчеру. После устранения закупорки нужна медицинская оценка.')

def emergency_reply(question,age=None):
    q=norm(question)
    if re.search(r'бабушк|дедушк|взросл|муж\b|мама\b|папа\b|\bя\b|\bмне\b',q) and not re.search(r'ребен|малыш|сын|доч',q):
        return 'Немедленно вызовите скорую помощь — 112 или 103. Включите громкую связь. ' + ('Сообщите диспетчеру, что пострадал взрослый, и наблюдайте за сознанием и дыханием. '
                       'При отсутствии реакции и нормального дыхания начинайте СЛР по указаниям диспетчера; детскую схему не применяйте. '
                       'Не давайте еду, питьё или лекарства человеку с нарушенным сознанием. Не оставляйте его одного.')
    if choking(q):return choking_reply(age)
    if re.search(r'судорог|судорожн\w* приступ',q):
        return ('Немедленно вызовите скорую помощь — 112 или 103, сообщите о судорогах и времени их начала. '
                'Не разжимайте зубы ложкой или пальцами и ничего не кладите в рот. '
                'Не удерживайте судорожные движения силой. Уберите опасные предметы рядом, '
                'подложите под голову что-то мягкое и засеките длительность приступа. '
                'До полного восстановления не давайте еду, питьё или лекарства через рот. '
                'После прекращения судорог, если дыхание нормальное, осторожно поверните человека на бок '
                'и оставайтесь рядом. Если нормального дыхания нет, сразу сообщите диспетчеру '
                'и начинайте СЛР по его указаниям. Не ждите ответа чата.')
    if battery_ingestion(q):return battery_reply()
    if re.search(r'отек|опух',q) and re.search(r'губ|язык|горл|лиц',q) and re.search(r'дыш|дыхан',q):
        posture = ('Младенца поддерживайте на спине горизонтально на руках, не лицом вниз; не держите столбиком. ' if age is not None and age < 12 else
                   'Уложите ребёнка; не позволяйте ему вставать и ходить. ' if age is not None else
                   'До года поддерживайте на спине горизонтально на руках, не столбиком. С года уложите, не позволяйте вставать и ходить. ')
        return ('Немедленно вызовите скорую помощь — 112 или 103: отёк с нарушением дыхания после еды может быть тяжёлой аллергической реакцией. '
                'Прекратите кормление. Не давайте есть или пить. ' + posture +
                'Если лежать мешает дыханию, следуйте указаниям диспетчера о положении с поддержкой и вытянутыми ногами; не поднимайте резко. '
                'Если есть назначенный этому ребёнку автоинъектор адреналина и план действий врача, примените его по этому плану; не ждите действия антигистаминного. '
                'При отсутствии сознания и нормального дыхания начинайте СЛР по указаниям диспетчера. Не ждите чата.')
    call = 'Немедленно вызовите скорую помощь — 112 или 103. Включите громкую связь или поручите вызов другому взрослому. Не ждите ответа чата или записи к врачу. '
    if re.search(r'кровотеч|кровь[^.!?\n]{0,35}(?:льется|хлещет|не останавливается)',q):
        return call + ('При сильном наружном кровотечении из раны сразу прижмите её через чистую ткань или салфетку, по возможности в перчатках; держите давление. '
                       'Если в ране предмет или выступает кость, не давите на них и не извлекайте: сообщите диспетчеру, выполняйте его указания. '
                       'Не откладывайте остановку кровотечения до приезда бригады. Не оставляйте пострадавшего одного, наблюдайте за дыханием.')
    if re.search(r'ожог|обожг|ошпар',q) and not re.search(r'хим|кислот|щелоч|электр|ток',q):
        return call + ('Прекратите воздействие тепла, если это безопасно. Охлаждайте только обожжённый участок прохладной проточной водой 20 минут; остальное тело держите в тепле. '
                       'Не используйте лёд, масло или крем, не прокалывайте пузыри и не отрывайте прилипшую одежду. '
                       'Не погружайте ребёнка целиком в холодную воду. После охлаждения прикройте ожог чистой неприлипающей повязкой. Следуйте диспетчеру.')
    if re.search(r'отрав|выпил|выпила|проглот|надышал',q):
        return call + ('Сообщите название вещества, примерное количество и время. Не вызывайте рвоту, не давайте еду, питьё или лекарства наугад и не пытайтесь нейтрализовать вещество. '
                       'Не подвергайте себя воздействию яда. Сохраните упаковку, если это не задержит помощь. Следите за сознанием и дыханием, выполняйте указания диспетчера.')
    if re.search(r'без созн|не реагир|не просыпа|не (?:могу|удается) разбуд',q) and re.search(r'дышит нормально|дыхание нормальное',q) and not re.search(r'не дышит нормально|не дышит|перестал дыш',q):
        return call + ('Если нормальное дыхание сохраняется, поддерживайте проходимость дыхательных путей; при отсутствии подозрения на травму осторожно поверните на бок. '
                       'При подозрении на травму не перемещайте без необходимости; если дыхательные пути иначе не сохранить, следуйте диспетчеру. '
                       'Ничего не давайте через рот, постоянно проверяйте дыхание. Если оно перестало быть нормальным, сразу сообщите диспетчеру и начинайте СЛР по его указаниям.')
    if re.search(r'не дыш|перестал\w* дыш|без созн|не реагир|не (?:могу|удается) разбуд|не просыпа',q):
        return call + ('Проверьте реакцию и нормальное дыхание, откройте дыхательные пути; оценка дыхания — не более 10 секунд. Редкие судорожные вздохи не являются нормальным дыханием. '
                       'Если ребёнок не реагирует и не дышит нормально, положите его на спину на твёрдую поверхность и начинайте СЛР: '
                       '5 начальных спасательных вдохов, затем 30 надавливаний и 2 вдоха; обученные детской СЛР используют 15:2. '
                       'Если не можете делать вдохи, выполняйте надавливания. Диспетчер подскажет технику по возрасту. '
                       'Если без сознания, но дышит нормально, поддерживайте проходимость дыхательных путей; при отсутствии подозрения на травму поверните на бок. '
                       'При травме не перемещайте без необходимости; если иначе дыхательные пути не сохранить, следуйте диспетчеру. Постоянно проверяйте дыхание.')
    return call + ('Оставайтесь рядом, сообщите диспетчеру симптомы, возраст и адрес. Следите за сознанием и дыханием. '
                   'Ребёнку в сознании с затруднённым дыханием разрешите удобное положение, не заставляйте ложиться. '
                   'Не трясите ребёнка, не заставляйте есть или пить и не давайте лекарства наугад. '
                   'Если перестал реагировать или дышать нормально, немедленно сообщите диспетчеру и начинайте первую помощь по его указаниям.')



def battery_ingestion(question):
    q=norm(question)
    return bool(re.search(r'батаре[йя]',q) and re.search(r'проглот|съе[лс]|во рту|пропал|не хватает|не могу найти',q))


def battery_reply():
    return ('При подозрении, что ребёнок проглотил батарейку, нужна немедленная медицинская помощь — '
            'даже если он играет и выглядит здоровым. Вызовите скорую — 112 или 103 сейчас, сообщите о батарейке и следуйте '
            'указаниям диспетчера. Не ждите симптомов или выхода батарейки со стулом и не вызывайте рвоту. '
            'Если это не задержит помощь, возьмите игрушку или упаковку батарейки с собой. '
            'Чат не может исключить проглатывание.')

def boundary_request(question):
    q=norm(question)
    return bool(re.search(r'врач|педиатр|специалист|осмотр',q) and re.search(r'перестать|не обращаться|не ходить|отказаться|заменит|вместо врача|можно без',q))

def boundary_reply():
    return ('ИИ может помочь понять информацию и подготовить вопросы, но не заменяет осмотр и оценку здоровья ребёнка врачом. '
            'Не отказывайтесь от назначенного наблюдения или обследования на основании ответа чата. Если общение с врачом не подходит, '
            'можно получить второе мнение. При новых тревожных симптомах обращение нельзя откладывать ради переписки.')

def review(answer,state,age):
    """Replace a detected unsafe paragraph, keeping the rest of the useful reply."""
    q=norm(next((m.get('text','') for m in reversed(state.get('messages',[])) if m.get('role')=='user'),''))
    if boundary_request(q):return boundary_reply()
    parts=re.split(r'\n\s*\n',answer)
    result=[]
    for part in parts:
        a=norm(part)
        if age is not None and age<12 and re.search(r'накрой|укрой|накрыть|укрыть',a) and re.search(r'плед|одеял|покрывал',a) and not re.search(r'не (?:накры|укры)|нельзя|не нужно',a):
            part='Для сна оставьте твёрдый ровный матрас свободным от пледов, одеял и других мягких предметов. Для тепла подойдёт одежда или спальный мешок по размеру без утяжеления.'
        if age is not None and age<60 and re.search(r'яблок',a) and re.search(r'давайте|дайте|предложите|можно дать',a) and re.search(r'сыр|тверд|крупн\w* кус|половин|держател',a) and not re.search(r'не (?:давайте|дайте|предлагайте)|нельзя',a):
            part='Твёрдое сырое яблоко крупным куском не подходит для тренировки жевания. Выбирайте безопасную по навыкам текстуру: приготовленное до мягкости или мелко натёртое яблоко. При повторных трудностях жевания или глотания обсудите питание с педиатром.'
        if re.search(r'поперх|давится',a) and re.search(r'практик|навык[^.!?]{0,40}(?:придет|дойдет)|обычно[^.!?]{0,40}справля',a):
            part='При повторных поперхиваниях даже маленькими глотками остановите кормление и обсудите глотание с педиатром. Не продолжайте через трудности ради тренировки. Если ребёнок не может дышать или эффективно кашлять, нужна немедленная первая помощь и вызов 112.'
        if age is not None and age<12 and re.search(r'пелен',a) and re.search(r'постепенн|одного[^.!?]{0,30}сна',a) and re.search(r'переворач|перевер',q):
            part='При попытках переворачиваться пеленание прекращают сразу для каждого сна; постепенный переход с сохранением пеленания на другие сны не подходит.'
        if re.search(r'если[^.!?]{0,50}(?:что-то|что-либо|люб\w*)[^.!?]{0,60}(?:перечислен|замет)',a) and re.search(r'в ближайшее время',a) and re.search(r'посинен|синие губ|паузы в дыхании',norm(answer)):
            part='При посинении, паузах с изменением цвета или затруднении дыхания звоните 112 немедленно. Менее выраженные стойкие изменения дыхания обсудите с педиатром; по переписке их причину не определить.'
        if re.search(r'ребен|малыш|на кормление',a) and re.search(r'трудно разбудить|не удается разбудить|не просыпается',a) and re.search(r'сегодня|в ближайшее время|запишитесь',a):
            part=('Если ребёнка трудно разбудить или он не реагирует как обычно, звоните 112 немедленно; не ждите записи к врачу. '
                  'Заметное уменьшение мочеиспусканий или ослабление кормления также требуют медицинской оценки сегодня. '
                  'При нарушении дыхания, посинении или потере сознания — немедленно 112.')
        if re.search(r'право[^.!?]{0,100}не всегда',a) and re.search(r'объя|поцел|телесн',q):
            part='Ребёнок может отказаться от объятий и поцелуев. Предложите другое приветствие и помогите взрослым уважать его отказ.'
        if re.search(r'зафиксир\w* руки|обнять сзади',a) and re.search(r'бьет|куса|истер|удар',q):
            part='Отойдите на безопасное расстояние, уберите опасные предметы и мягко преградите удар, если это нужно для защиты. Не фиксируйте руки и не удерживайте силой ради прекращения эмоций.'
        result.append(part)
    answer='\n\n'.join(result)
    a=norm(answer)
    if age is not None and age<12 and 'пелен' in a and not re.search(r'попытк\w* переворач|при переворот|прекратите пелен|пеленание прекращ',a):
        answer+='\n\nПри первых попытках переворачиваться пеленание прекращают. Возраст не подтверждает отсутствие этого навыка.'
    if re.search(r'машин|автомобил|дорог',q) and re.search(r'корм|еда|есть|перекус',q):
        answer='Для еды сначала остановите автомобиль в безопасном разрешённом месте. Не кормите ребёнка в движении; во время еды нужны устойчивое вертикальное положение и наблюдение взрослого.\n\n'+answer
        answer=re.sub(r'[^.!?\n]*если есть риск поперхнуться[^.!?\n]*[.!?]?', '',answer,flags=re.I)
    return answer

def valid_language(answer,question):
    # Reject corrupted output instead of silently deleting a possibly vital term.
    if re.search(r'[A-Za-z]+[А-Яа-яЁё]+|[А-Яа-яЁё]+[A-Za-z]+',answer):return False
    if re.search(r'[\u3400-\u9fff]',answer) and not re.search(r'[\u3400-\u9fff]|китайск|японск|переведи',question,re.I):return False
    return True
