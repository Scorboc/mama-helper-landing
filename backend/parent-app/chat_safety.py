def followup_reply(question, messages):
    """Keep an unresolved, explicitly current harm risk out of the model queue."""
    q=question.lower().replace('ё','е')
    if re.search(r'(?:врач|помощь|взрослый|бригада).{0,25}(?:приехал|пришел|пришла|рядом|здесь)|риск (?:прошел|миновал)',q):return None
    if not re.search(r'помощь сейчас|ждать[^.!?\n]{0,65}(?:ответ|чат)|дыхательн|заземл|упражнен|успокоиться',q):return None
    recent=[m for m in (messages or [])[-6:] if isinstance(m,dict)]
    acute=any(m.get('role')=='user' and re.search(r'теряю контроль|сейчас.*(?:ударю|убью)|боюсь[^.!?\n]{0,40}ударю',str(m.get('text','')).lower()) for m in recent)
    handed=any(m.get('role')=='assistant' and '112' in str(m.get('text','')) for m in recent)
    if not (acute and handed):return None
    last_acute=max(i for i,m in enumerate(recent) if m.get('role')=='user' and re.search(r'теряю контроль|сейчас.*(?:ударю|убью)|боюсь[^.!?\n]{0,40}ударю',str(m.get('text','')).lower()))
    if any(m.get('role')=='user' and re.search(r'(?:врач|помощь|взрослый|бригада).{0,25}(?:приехал|пришел|пришла|рядом|здесь)|риск (?:прошел|миновал)',str(m.get('text','')).lower()) for m in recent[last_acute+1:]):return None
    return ('Не ждите следующего ответа чата — звоните 112 сейчас и сообщите, что есть риск '
            'навредить ребёнку и нужна помощь. Если ребёнок уже в безопасном месте, оставьте его '
            'там, отойдите от опасных предметов и позовите взрослого, которому доверяете, если '
            'он доступен. Выполняйте указания диспетчера.')


