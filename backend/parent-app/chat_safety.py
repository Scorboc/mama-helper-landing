    answer=re.sub(r'[^.!?\n]*партн[её]р[^.!?\n]*без\s+поправок[^.!?\n]*[.!?]?',
                  'Можно оставить взрослому пространство для безопасного ухода. Если действие создаёт риск ребёнку, остановите его и объясните, что нужно изменить.',answer,flags=re.I)
