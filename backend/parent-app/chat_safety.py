"""Conservative, local safety replies; no provider call or diagnosis.

References reviewed 2026-09-20:
https://www.gosh.nhs.uk/conditions-and-treatments/conditions-we-treat/button-batteries-using-them-safely/
https://www.healthychildren.org/English/ages-stages/prenatal/decisions-to-make/Pages/Choosing-a-Crib.aspx
https://www.cuh.nhs.uk/rosie-hospital/maternity/maternal-wellbeing-and-mental-health-new/faqs/
These guards supplement the system instructions; they are not clinical triage.
"""
import re
from datetime import date
import importlib.util
from pathlib import Path

_policy_spec=importlib.util.spec_from_file_location("content_policy",Path(__file__).with_name("content_policy.py"))
_policy=importlib.util.module_from_spec(_policy_spec);_policy_spec.loader.exec_module(_policy)

def review(answer, state):
    """Conservative post-check of known dangerous suggestions, not clinical triage."""
    if re.search(r'надуйте|игра[^\n]*воздушн[^\n]*шар|держите[^\n]*шарик',answer.lower()):
        return 'Воздушные шарики для этой игры использовать не нужно: лопнувшие части опасны. '+_policy.play(state.get('profile'))
    if re.search(r'трудно (?:глотать или )?дышать|затруднен[^\n]*дыхани',answer.lower().replace('ё','е')) and '112' not in answer:
        answer += '\n\nПри затруднении дыхания немедленно звоните 112; не ждите планового приёма.'
    return answer

def reply(question, profile=None):
    q=question.lower().replace('ё','е')
    if re.search(r'не дыш|без созн|судорог|не хочу жить|покончить|убить себя',q):
        return None  # The existing emergency handler must take priority.
    if re.search(r'теряю контроль|сейчас.*(?:ударю|убью)|хочу.*навредить',q) and not re.search(r'не хочу.*навредить',q):
        return ('Если прямо сейчас есть риск навредить себе или ребёнку, звоните 112. '
                'Положите малыша в безопасную кроватку, отойдите от опасных предметов и позовите '
                'взрослого, которому доверяете. Не оставайтесь с этой ситуацией один на один и не ждите чата.')
    if re.search(r'мочится в трус|мокр[^.]*трус|писа[^.]*штан|недержан',q) and re.search(r'снова|стал|начала|вдруг|после|почему|назло',q):
        return ('По переписке нельзя определить причину мокрых трусиков и приписать ребёнку намерение '
                'досадить. Не ругайте и не стыдите: спокойно помогите переодеться. Если ребёнок раньше '
                'был сухим, а теперь эпизоды повторяются, запишитесь к педиатру: нужно учитывать '
                'возможные физические причины, а не объяснять всё ревностью или стрессом. '
                'Не ограничивайте питьё ради сухости. Отметьте, когда это происходит, есть ли запор, '
                'боль или частые позывы. При боли или жжении, температуре, крови в моче или заметном '
                'ухудшении самочувствия нужна медицинская помощь в тот же день. '
                'Можно уделить ребёнку спокойное личное время, но это не заменяет оценку причины.')
    if re.search(r'просып|ночью|ночь',q) and re.search(r'ищу|ищем|ищет|обыскив',q) and re.search(r'младен|малыш|ребен',q):
        return ('Просыпаться в таком страхе тяжело. По переписке нельзя определить причину, '
                'но из-за страха спать стоит обратиться к врачу или специалисту по психическому '
                'здоровью уже сейчас, не дожидаясь ухудшения. На эту ночь по возможности попросите '
                'близкого помочь с уходом, чтобы у вас был перерыв на сон. Малышу нужно отдельное '
                'безопасное спальное место: на спине, на твёрдой ровной поверхности, без подушек '
                'и мягких предметов. Если проснулись в испуге, включите мягкий свет, почувствуйте '
                'опору и напомните себе, где находится малыш. Не нужно вводить ритуал многократных '
                'проверок; при этом продолжайте отвечать на его реальные потребности в кормлении '
                'и уходе. Кто мог бы помочь вам отдохнуть сегодня?')
    if re.search(r'кухн',q) and re.search(r'игр|занят',q) and re.search(r'реч|слов|экран|мультик',q):
        return 'Начинайте, когда готовка уже закончена и горячие предметы убраны. '+_policy.play(profile)

    if re.search(r'кроват',q) and re.search(r'щеп|крошится|отслаива|заноз',q):
        return ('Если от кроватки отходят щепки или покрытие, пока не используйте её: ребёнок может '
                'пораниться или проглотить обломок. Организуйте другое исправное спальное место по возрасту '
                'и обратитесь к изготовителю по поводу ремонта или замены. Не наносите горькие вещества, '
                'не закрывайте повреждение самодельными накладками и не пытайтесь сделать его безопасным '
                'перестановкой кровати. Для жевания предложите целый прорезыватель, предназначенный для '
                'возраста ребёнка. Если есть травма рта или подозрение на проглоченную щепку — нужна '
                'медицинская оценка; при затруднении дыхания сразу звоните 112.')
    if re.search(r'голов|волос',q) and re.search(r'мыть|помыть|моем|мытья',q) and re.search(r'бо|страх|дрож|паник|удерж',q):
        return ('Удерживать ради мытья головы не нужно. Можно временно ограничиться необходимой '
                'гигиеной и вернуть ребёнку контроль: «Сегодня только намочим кончики; скажешь стоп — '
                'остановлюсь». Начните с игры с куклой и сухой мочалкой, затем предложите влажную '
                'мочалку — только с согласия ребёнка, без воды и средства в глаза. Пусть выберет '
                'полотенце или сам держит маленькую чашку. Оставайтесь рядом всё время у воды. '
                'Не заклеивайте глаза, не закрывайте лицо и не обещайте «не мыть», чтобы потом сделать '
                'это неожиданно. Не обязательно пройти все шаги за один раз. Если страх усиливается '
                'или есть боль и раздражение кожи, обсудите это с педиатром.')
    if re.search(r'спит|спать|засып|сон',q) and re.search(r'диван|кресл',q) and re.search(r'младен|месяч|малыш|ребен',q):
        return ('Вы очень устали, и сейчас важнее всего безопасно пережить ночь. Не засыпайте с '
                'младенцем на диване или в кресле. Если клонит в сон, положите малыша на спину в '
                'отдельную исправную кроватку или люльку с твёрдым ровным матрасом, без подушек, '
                'бортиков, игрушек и свободных покрывал. Даже если он протестует, это безопаснее, '
                'чем уснуть с ним на руках. Не грейте матрас грелкой и не снимайте стенку обычной '
                'кроватки. Если возможно, позвоните близкому и попросите подменить вас. Если вы '
                'одна, сначала положите ребёнка безопасно, затем сделайте короткую паузу рядом. '
                'Повторяющиеся трудности со сном и кормлением обсудите с педиатром. Есть ли сейчас '
                'рядом отдельное безопасное спальное место для малыша?')
    if re.search(r'игр|занят|моторик',q) and re.search(r'в рот|во рту|бусин|крупа|мелк',q):
        return _policy.play(profile)+'\n\nПрисмотр не делает мелкие предметы безопасными. Не используйте бусины, крупу и съёмные мелкие детали.'
    if re.search(r'батаре[йя]',q) and re.search(r'проглот|съе[лс]|во рту|пропал|не хватает|не могу найти',q):
        return ('При подозрении, что ребёнок проглотил батарейку, нужна немедленная медицинская помощь — '
                'даже если он играет и выглядит здоровым. Звоните 112 сейчас, сообщите о батарейке и следуйте '
                'указаниям диспетчера. Не ждите симптомов и не вызывайте рвоту. Если это не задержит помощь, '
                'возьмите игрушку или упаковку батарейки с собой. Чат не может исключить проглатывание.')
    if re.search(r'голов|лбом',q) and re.search(r'бь[ею]т|бить|бил|стуч|удар',q):
        return ('В такой ситуации сначала важно защитить ребёнка от травмы. Оставайтесь рядом, уберите '
                'опасные предметы и спокойно помогите отойти от твёрдой поверхности; не наказывайте и не '
                'оставляйте его одного во время ударов. Можно коротко назвать чувство: «Ты злишься, я рядом».'
                '\n\nНе обкладывайте кроватку подушками и не привязывайте мягкие бортики: они создают '
                'дополнительные риски. Проверьте исправность кроватки. По переписке нельзя установить '
                'причину ударов: повторяющиеся эпизоды, особенно во сне или с повреждениями, обсудите с '
                'педиатром. При потере сознания, судорогах, повторной рвоте или резком ухудшении после '
                'удара — немедленно 112.')
    intrusive=re.search(r'навязчив|пугает.*мысл|пугают.*мысл|страшн.*картин',q)
    denial=re.search(r'не хочу|не собираюсь|не желаю|этого не хочу',q)
    immediate=re.search(r'не могу останов|теряю контроль|сейчас.*(?:ударю|сделаю|убью)|есть план',q)
    if intrusive and denial and not immediate:
        return ('Да, можем спокойно поговорить. Пугающая нежеланная мысль сама по себе не означает, что '
                'вы хотите её осуществить. При этом ваш страх заслуживает поддержки.'
                '\n\nСейчас вы и ребёнок в безопасности? Если да, попробуйте почувствовать опору под ногами '
                'и назвать несколько предметов вокруг. Можно попросить близкого побыть рядом. Если такие '
                'мысли повторяются, мешают спать или заботиться о себе, обратитесь к специалисту по '
                'психическому здоровью — диагноз по чату поставить нельзя.'
                '\n\nЕсли появится желание действовать или ощущение потери контроля, положите малыша '
                'в безопасную кроватку, позовите взрослого и звоните 112. Что сейчас пугает вас сильнее всего?')
    return None
