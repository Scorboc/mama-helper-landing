"""Reviewed adult self-help; not assessment, diagnosis or psychotherapy.

Only explicit practice requests use a local reply. Open support conversations
remain with the chat model and its approved instructions. No stored data change.
"""
import re

SOURCES = {
    'breathing': ('NHS: мягкое дыхание при стрессе', 'https://www.nhs.uk/mental-health/self-help/guides-tools-and-activities/breathing-exercises-for-stress/'),
    'grounding': ('ВОЗ: навыки самопомощи при стрессе', 'https://www.who.int/publications/i/item/9789240003927'),
    'small_step': ('NHS: помощь при стрессе', 'https://www.nhs.uk/mental-health/feelings-symptoms-behaviours/feelings-and-symptoms/stress/'),
}

BREATHING = (
    'Можно попробовать мягкое дыхание, если вам это сейчас подходит. '
    'Устройтесь удобно; если сидите, почувствуйте опору спины и ног, если это возможно. '
    'Позвольте дыханию идти в удобном темпе, без усилия: мягкий вдох через нос и '
    'мягкий выдох через рот. Не старайтесь вдохнуть побольше и не задерживайте дыхание. '
    'Счёт необязателен; если удобнее с ним, можно спокойно считать на вдохе и выдохе '
    'до удобного числа, не обязательно до пяти. Можно начать с нескольких удобных '
    'циклов; не нужно выдерживать таймер. Если становится неприятно, кружится голова '
    'или усиливается тревога, прекратите упражнение и вернитесь к обычному дыханию. '
    'Это необязательный способ сделать паузу, он может не подойти и не заменяет лечение.'
)
GROUNDING = (
    'Можно попробовать вернуть внимание к тому, что вокруг, без управления дыханием. '
    'С открытыми глазами заметьте один нейтральный предмет, его цвет или форму, '
    'затем один звук и удобную точку опоры тела — например, спинку стула. '
    'Можно использовать только доступные и приятные вам ощущения; не нужно '
    'проходить обязательный список или вспоминать пугающее событие. '
    'Если неприятно, остановитесь. Цель — заметить настоящий момент, а не заставить '
    'себя немедленно успокоиться. Это короткая адаптация самопомощи, не лечение.'
)


def normalize(text):
    return str(text or '').lower().replace('ё', 'е')


def adult_request(question):
    q = normalize(question)
    # Do not route instructions for the child to an adult exercise.
    if re.search(r'(?:ребенку|малышу|сыну|дочке|дочери)[^.!?\n]{0,55}(?:дыхательн|заземл|успокои)', q):
        return False
    if re.search(r'(?:дыхательн|заземл)[^.!?\n]{0,55}(?:для ребенка|ребенку|малышу)', q):
        return False
    return bool(re.search(r'\b(?:я|мне|меня|взросл\w*|плачу|беременна)\b|плохо сплю|для мамы|маме|у мамы|веду (?:машину|автомобиль)|за рулем', q))


def no_advice(question):
    return bool(re.search(r'без совет|не (?:нужны|хочу|давай\w*) совет|не (?:предлагай|нужны|хочу) упражн|только (?:выслуш|послуш)', normalize(question)))


def urgent_reply(question):
    """Narrow present-tense adult red flags; never label them as stress."""
    q = normalize(question)
    if re.search(r'(?:ребенку|малышу|сыну|дочке|дочери|у ребенка)[^.!?\n]{0,50}(?:трудно|тяжело|не может)[^.!?\n]{0,25}дыш',q):
        return None  # A parent's pregnancy or fear does not change the symptom's subject.
    if not adult_request(q):
        return None
    current = bool(re.search(r'сейчас|внезапно|нараста|начал|стало|сдавил|сильн\w* (?:боль|давление|одышк)', q))
    chest = bool(re.search(r'(?:давит|сдавил\w*|сжимает|тяжесть|боль)\s+(?:мне\s+)?(?:в\s+)?груд', q))
    breathing = bool(re.search(r'не могу (?:нормально )?дышать|(?:тяжело|трудно) дышать|не хватает воздуха|не могу сказать|синеют губы', q))
    breast = bool(re.search(r'уплотнен|сосок|сцеж|мастит|молочн\w* желез|кормлю грудью', q))
    if breast and not breathing and not re.search(r'давит|сдавил|сжимает|внезапн\w* боль|сильн\w* боль', q):
        return None  # Breast symptoms are not interchangeable with chest pain.
    if current and (chest or breathing):
        # A mention of yesterday must not suppress a new emergency today.
        active_q = re.split(r'но сейчас|а сейчас|теперь', q)[-1]
        if re.search(r'прошл\w*|вчера|раньше', active_q):
            return None
        chest_now = chest and not re.search(r'нет (?:боли|давления)|не (?:болит|давит)', active_q)
        breath_now = breathing and not re.search(r'нет одышки|дышу (?:нормально|свободно)|дыхание нормальное', active_q)
        if not (chest_now or breath_now):
            return None
        conditional = bool(re.search(r'если|боюсь,? что|что делать,? когда', active_q))
        opening = 'Если это происходит сейчас, звоните 112: ' if conditional else 'Сейчас звоните 112: '
        return (opening + 'внезапную или сильную боль, давление в груди и '
                'выраженное затруднение дыхания нельзя списывать на стресс по переписке. '
                'Не откладывайте помощь ради дыхательной практики и не садитесь за руль. '
                'Если рядом есть человек, попросите его остаться с вами; следуйте указаниям диспетчера.')
    if re.search(r'слышу голоса[^.!?\n]*(?:которых нет|приказыва|не слышат)|вижу[^.!?\n]*то,? чего нет', q) and not re.search(r'раньше|вчера|не слышу|боюсь, что|если', q):
        return ('Нужна срочная медицинская оценка сегодня; по чату причину таких ощущений '
                'установить нельзя. Если доступен безопасный взрослый, попросите побыть рядом '
                'и помочь обратиться за медицинской помощью. При риске причинить вред, '
                'сильной растерянности или невозможности обеспечить безопасность звоните 112 '
                'сейчас. Не откладывайте обращение ради упражнения.')
    return None


def with_source(answer, question, key):
    if re.search(r'источник|официальн|документ|основан|ссылк|\bвоз\b|\bnhs\b', normalize(question)):
        title, url = SOURCES[key]
        return answer + '\n\nОснова: [' + title + '](' + url + '). Текст адаптирован для короткого ответа MAMA; организация не оценивала наш чат.'
    return answer


def reply(question):
    q = normalize(question)
    urgent = urgent_reply(q)
    if urgent:
        return urgent
    if re.search(r'\b(?:я|мне)\b[^.!?]{0,55}только (?:ваши|твои) решени',q):
        return ('Помогу выбрать понятный следующий шаг и объясню его причину. '
                'Если для безопасности важны недостающие сведения, их нужно уточнить; '
                'некоторые вопросы требуют оценки специалиста. Решения, подходящие '
                'вашей семье, остаются за вами — не нужно передавать их целиком ИИ.')
    if re.search(r'только (?:с тобой|к тебе|с ии|ии)|ни к кому.*только',q) and re.search(r'обращ|обща|буду|говор',q):
        return ('Чат может помогать разобраться в вопросах, но не заменяет поддержку '
                'людей и профессиональную помощь. Здесь нет человека, который постоянно '
                'наблюдает за вами или может полностью оценить безопасность. '
                'Вы можете выбирать, кому доверять и какую помощь принимать; '
                'сохранять связь с безопасным близким или специалистом тоже важно.')
    if re.search(r'партнер|муж|близк',q) and re.search(r'угрож|запугив',q) and not re.search(r'не угрож|не запугив',q) and re.search(r'переписк|поставить[^.!?]{0,25}место|контрол|боюсь|удар',q):
        return ('Угрозы — серьёзная ситуация. Фраза, чтобы '
                '«поставить на место», может усилить риск, поэтому не предлагаю '
                'конфронтацию. Не сообщайте планы человеку, который угрожает. '
                'Если безопасно, свяжитесь с доверенным человеком или службой помощи '
                'при домашнем насилии с устройства, к которому партнёр не имеет доступа. '
                'Не сохраняйте доказательства на контролируемом устройстве, если это '
                'повышает риск. При непосредственной опасности для вас или ребёнка '
                'звоните 112. Вы не обязаны сначала убедить партнёра или ждать ухудшения.')
    if adult_request(q) and re.search(r'две недели|несколько недель|месяц|почти каждый день',q) and re.search(r'плачу|плохо сплю|не раду|безнадеж|не справля',q):
        return ('Так долго жить со слезами или нарушенным сном может быть тяжело. '
                'По чату причину определить нельзя, и это не стоит сводить к обычной '
                'усталости. Обратитесь к врачу или специалисту по психическому здоровью '
                'уже сейчас: не нужно ждать ещё несколько недель или сначала пробовать '
                'все упражнения. Можно начать с терапевта или врача, который наблюдает '
                'вас после родов; сообщите, как долго это длится и как влияет на жизнь. '
                'Если появится непосредственный риск навредить себе или ребёнку — '
                'нужна срочная помощь, 112. Поддержка возможна и без такого риска.')
    if not adult_request(q) or no_advice(q):
        return None
    request = bool(re.search(r'покаж|дай|хочу|как |попроб|можно|посовет|научи|практик|упражнен', q))
    if not request:
        return None
    breath = bool(re.search(r'дыхательн|упражнен[^.!?\n]{0,30}дыхан|как (?:мне )?дышать|4\s*[-–/]\s*7\s*[-–/]\s*8|дышать в пакет', q))
    grounding = bool(re.search(r'заземл|без (?:управления )?дыхан', q))
    practice = breath or grounding or bool(re.search(r'практик|упражнен|закрыт\w* глаз', q))
    if practice and re.search(r'за рулем|веду (?:машину|автомобиль)|вожу (?:машину|автомобиль)', q):
        return ('Во время вождения продолжайте следить за дорогой. Чтобы попробовать '
                'упражнение, сначала остановитесь в разрешённом безопасном месте. '
                'Практика может подождать; не закрывайте глаза и не отвлекайтесь на '
                'счёт или ощущения за рулём.')
    if (breath or grounding) and re.search(r'оставить[^.!?\n]{0,30}(?:ребенка|малыша)[^.!?\n]{0,25}одного|(?:ребенку|малышу)[^.!?\n]{0,25}нужен присмотр', q):
        return ('Пока ребёнку нужен присмотр, продолжайте необходимый уход. Не оставляйте '
                'его одного ради упражнения. Пауза может подождать безопасного момента; '
                'это не задача, которую обязательно выполнить сейчас.')
    rejected = bool(re.search(r'не (?:хочу|могу|подходит)[^.!?\n]{0,30}дых|дых[^.!?\n]{0,35}(?:не помог|не подходит|не хочу)', q))
    if breath and re.search(r'(?:от|после|во время)[^.!?\n]{0,45}дых[^.!?\n]{0,60}(?:круж|онем|хуже|дурно)', q):
        return ('Прекратите упражнение и вернитесь к обычному дыханию, без задержек и '
                'форсированных вдохов. Устройтесь устойчиво и удобно; не продолжайте через '
                'неприятные ощущения. Если они не проходят, повторяются или нарастают, '
                'обратитесь за медицинской помощью. При выраженной одышке, сильной боли '
                'в груди, обмороке или резком ухудшении звоните 112. По чату нельзя '
                'установить причину этих ощущений.')
    if breath and not rejected:
        explanation = ('Для короткой самопомощи выберем мягкий вариант без задержек '
                       'дыхания и специального приспособления, чтобы не добавлять усилие '
                       'или необходимость выдерживать схему. ') if re.search(r'4\s*[-–/]\s*7\s*[-–/]\s*8|дышать в пакет', q) else ''
        return with_source(explanation + BREATHING, question, 'breathing')
    if grounding or re.search(r'опор\w*[^.!?\n]{0,30}(?:тревог|стресс)', q) or breath and rejected:
        answer = GROUNDING
        if re.search(r'не вижу|незряч|не могу смотреть|не слышу|глух', q):
            answer = ('Можно выбрать только доступное вам ощущение: например, удобный '
                      'контакт тела со спинкой стула или другой опорой. Если это приятно, '
                      'заметьте, какой он — мягкий, твёрдый, тёплый. Другие органы чувств '
                      'использовать не обязательно; управлять дыханием не нужно. '
                      'Прекратите, если неприятно. Цель — заметить настоящий момент, '
                      'не заставлять себя успокоиться. Это самопомощь, не лечение.')
        return with_source(answer, question, 'grounding')
    return None


def review(answer, question):
    """Catch known unsafe breathing instructions, without censoring warnings."""
    if not adult_request(question):
        return answer
    urgent = urgent_reply(question)
    if urgent:
        return urgent
    dangerous = r'задержи\w* дыхание|дыши\w* в (?:бумажный |полиэтиленовый )?пакет|дыши\w* (?:максимально|очень) глубоко|продолжа\w*[^.!?\n]{0,30}несмотря на головокружение|4\s*[-–/]\s*7\s*[-–/]\s*8'
    for sentence in re.split(r'[.!?\n]+', normalize(answer)):
        for match in re.finditer(dangerous, sentence):
            before = sentence[max(0, match.start()-28):match.start()]
            if not re.search(r'\bне\b|нельзя|избегайте|без |не рекоменду', before):
                if no_advice(question):
                    return 'Сейчас можно просто рассказать, что вам тяжелее всего, без упражнений и обязательного плана.'
                return with_source(BREATHING, question, 'breathing')
    return answer
